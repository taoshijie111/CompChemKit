#!/usr/bin/env python3
"""Validate `knowledge/` notes and keep the README index in sync.

Usage:
    python tools/build_index.py            # check notes + index freshness (exit 1 on problems)
    python tools/build_index.py --write    # validate, then rewrite the generated index block

Layout contract: one source -> one note at `<topic>/<YYYY>-<slug>.md`. The frontmatter dialect is
a deliberately tiny, flat subset of YAML parsed below, so the check needs no third-party
dependency. The index lives in README.md between the BEGIN:INDEX / END:INDEX comments; it is
generated by this script and must not be edited by hand.
"""

from __future__ import annotations

import argparse
import re
import sys
from datetime import date
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
BEGIN = "<!-- BEGIN:INDEX -->"
END = "<!-- END:INDEX -->"
SKIP_DIRS = {"tools"}
TYPES = {"paper", "review", "preprint", "blog", "docs", "talk", "dataset", "book", "thesis"}
READ_LEVELS = {"skim", "read", "deep"}
CONFIDENCE = {"high", "medium", "low"}
REQUIRED = ("title", "category", "type", "year", "added", "read", "confidence", "summary")
FILENAME_RE = re.compile(r"^(\d{4})-[a-z0-9]+(?:-[a-z0-9]+)*\.md$")
INDEX_RE = re.compile(re.escape(BEGIN) + r".*?" + re.escape(END), re.S)


class NoteError(Exception):
    """A note cannot be parsed or violates the frontmatter dialect."""


def note_paths():
    """Every candidate note path under knowledge/, as (absolute path, relative path)."""
    candidates = []
    for path in sorted(ROOT.rglob("*.md")):
        rel = path.relative_to(ROOT)
        if len(rel.parts) == 1:  # README.md / SKILL.md at the knowledge root
            continue
        if rel.parts[0] in SKIP_DIRS:
            continue
        if any(part.startswith(("_", ".")) for part in rel.parts):
            continue
        candidates.append((path, rel))
    return candidates


def parse_value(raw, line_number):
    if raw.startswith("[") and raw.endswith("]"):
        inner = raw[1:-1].strip()
        if not inner:
            return []
        return [unquote(item.strip(), line_number) for item in inner.split(",") if item.strip()]
    return unquote(raw, line_number)


def unquote(raw, line_number):
    if len(raw) >= 2 and raw[0] == raw[-1] and raw[0] in "\"'":
        return raw[1:-1]
    if raw[:1] in "\"'" or raw[-1:] in "\"'":
        raise NoteError(f"line {line_number}: unbalanced quotes in {raw!r}")
    return raw


def parse_frontmatter(path):
    """Parse the flat `key: value` block between the first two '---' lines."""
    lines = path.read_text(encoding="utf-8").splitlines()
    if not lines or lines[0].strip() != "---":
        raise NoteError("must start with a YAML frontmatter block ('---' on line 1)")
    close = None
    for index in range(1, len(lines)):
        if lines[index].strip() == "---":
            close = index
            break
    if close is None:
        raise NoteError("frontmatter block is not closed by a second '---' line")
    fields = {}
    for offset, line in enumerate(lines[1:close], start=2):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        match = re.match(r"^([A-Za-z_][A-Za-z0-9_-]*):[ \t]*(.*)$", line)
        if not match:
            raise NoteError(f"line {offset}: expected 'key: value', got {line.strip()!r}")
        key = match.group(1)
        if key in fields:
            raise NoteError(f"line {offset}: duplicate frontmatter field '{key}'")
        fields[key] = parse_value(match.group(2).strip(), offset)
    return fields


def validate_note(rel, fields):
    text = rel.as_posix()
    topic = rel.parts[0]
    problems = []
    for key in REQUIRED:
        if not str(fields.get(key, "")).strip():
            problems.append(f"{text}: missing required frontmatter field '{key}'")
    if not str(fields.get("doi") or fields.get("url") or "").strip():
        problems.append(f"{text}: needs a source link, 'doi:' or 'url:'")
    category = str(fields.get("category", "")).strip()
    if category and category != topic:
        problems.append(f"{text}: category '{category}' does not match directory '{topic}'")

    match = FILENAME_RE.match(rel.name)
    if not match:
        problems.append(f"{text}: filename must look like YYYY-<slug>.md (lower-case kebab-case)")
    year = str(fields.get("year", "")).strip()
    if year and not re.fullmatch(r"\d{4}", year):
        problems.append(f"{text}: year must be four digits, got {year!r}")
    elif match and year and int(match.group(1)) != int(year):
        problems.append(f"{text}: filename year {match.group(1)} does not match year: {year}")

    added = str(fields.get("added", "")).strip()
    if added:
        try:
            date.fromisoformat(added)
        except ValueError:
            problems.append(f"{text}: added must be an ISO date (YYYY-MM-DD), got {added!r}")

    for key, allowed in (("type", TYPES), ("read", READ_LEVELS), ("confidence", CONFIDENCE)):
        value = str(fields.get(key, "")).strip()
        if value and value not in allowed:
            problems.append(f"{text}: {key} must be one of {sorted(allowed)}, got {value!r}")

    title = str(fields.get("title", "")).strip()
    if len(title) > 140:
        problems.append(f"{text}: title is {len(title)} chars, keep it to 140 or fewer")
    summary = str(fields.get("summary", "")).strip()
    if len(summary) > 240:
        problems.append(f"{text}: summary is {len(summary)} chars, keep it to 240 or fewer")

    for key in ("tags", "related"):
        value = fields.get(key)
        if value not in (None, "") and not isinstance(value, list):
            problems.append(f"{text}: {key} must be an inline list, e.g. [{key}: a, b]")
    return problems


def normalize_link(value):
    value = str(value or "").strip().lower()
    value = re.sub(r"^(https?://(dx\.)?doi\.org/|doi:)", "", value)
    return value.rstrip("/")


def load_notes():
    errors = []
    loaded = []
    for path, rel in note_paths():
        if len(rel.parts) != 2:
            errors.append(
                f"{rel.as_posix()}: notes must live directly in a topic directory, "
                "e.g. <topic>/<YYYY>-<slug>.md"
            )
            continue
        try:
            fields = parse_frontmatter(path)
        except NoteError as exc:
            errors.append(f"{rel.as_posix()}: {exc}")
            continue
        errors.extend(validate_note(rel, fields))
        loaded.append((rel, fields))

    seen = {}
    for rel, fields in loaded:
        rel_text = rel.as_posix()
        for key in ("doi", "url"):
            value = normalize_link(fields.get(key))
            if not value:
                continue
            label = f"{key} {value!r}"
            if label in seen:
                errors.append(f"{rel_text}: duplicate {key} (also used by {seen[label]})")
            else:
                seen[label] = rel_text
        for target in fields.get("related") or []:
            if not (ROOT / str(target)).is_file():
                errors.append(f"{rel_text}: related note not found: {target}")

    notes = [{"rel": rel.as_posix(), "topic": rel.parts[0], "fields": fields} for rel, fields in loaded]
    return notes, errors


def short_source(fields):
    authors = str(fields.get("authors") or "").strip()
    venue = str(fields.get("venue") or "").strip()
    first_author = ""
    if authors:
        first_author = authors.split(";")[0].strip()
        if ";" in authors:
            first_author += " et al."
    parts = [part for part in (first_author, venue, str(fields["year"])) if part]
    if not parts:
        return str(fields.get("doi") or fields.get("url") or "")
    return ", ".join(parts)


def cell(value):
    return str(value).replace("|", "\\|")


def render_index(notes):
    if not notes:
        return (
            "_No notes yet. Copy `_template.md`, fill it in, and run "
            "`python tools/build_index.py --write`._"
        )
    topics = {note["topic"] for note in notes}
    rows = sorted(notes, key=lambda note: (note["topic"], -int(str(note["fields"]["year"])), note["rel"]))
    lines = [
        f"_{len(notes)} note(s) across {len(topics)} topic(s). "
        "Generated by `tools/build_index.py`; do not edit by hand._",
        "",
        "| Note | Topic | Source | Type | Added | Confidence | Takeaway |",
        "| --- | --- | --- | --- | --- | --- | --- |",
    ]
    for note in rows:
        fields = note["fields"]
        lines.append(
            "| "
            + " | ".join(
                cell(value)
                for value in (
                    f"[{fields['title']}]({note['rel']})",
                    note["topic"],
                    short_source(fields),
                    fields["type"],
                    fields["added"],
                    fields["confidence"],
                    fields["summary"],
                )
            )
            + " |"
        )
    return "\n".join(lines)


def main(argv=None):
    parser = argparse.ArgumentParser(
        description="Validate knowledge notes and check/refresh the generated README index."
    )
    parser.add_argument(
        "--write", action="store_true", help="rewrite the README index block instead of only checking"
    )
    args = parser.parse_args(argv)

    if not README.is_file():
        print(f"error: {README} not found", file=sys.stderr)
        return 1

    notes, errors = load_notes()
    if errors:
        for error in errors:
            print(f"error: {error}", file=sys.stderr)
        print(f"\n{len(errors)} problem(s) found; the index was not touched.", file=sys.stderr)
        return 1

    readme_text = README.read_text(encoding="utf-8")
    match = INDEX_RE.search(readme_text)
    if not match:
        print(f"error: README.md is missing the {BEGIN} / {END} markers", file=sys.stderr)
        return 1

    expected = BEGIN + "\n" + render_index(notes) + "\n" + END
    current = match.group(0)
    summary = f"{len(notes)} note(s), {len({note['topic'] for note in notes})} topic(s)"

    if args.write:
        if current == expected:
            print(f"OK: {summary}; README index already up to date.")
            return 0
        updated = INDEX_RE.sub(lambda _match: expected, readme_text, count=1)
        with README.open("w", encoding="utf-8", newline="\n") as handle:
            handle.write(updated)
        print(f"OK: {summary}; README index updated.")
        return 0

    if current != expected:
        print(
            "error: README index is stale - run `python tools/build_index.py --write`.",
            file=sys.stderr,
        )
        return 1
    print(f"OK: {summary}; frontmatter and README index are consistent.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
